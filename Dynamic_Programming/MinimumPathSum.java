class Solution {
    public int minPathSum(int[][] grid) {
        int m = grid.length, n = grid[0].length;
        int dp[][] = new int[m][n];
        dp[0][0] = grid[0][0];
        for (int i = 1; i < m; i++)
            dp[i][0] = dp[i - 1][0] + grid[i][0];
        for (int j = 1; j < n; j++)
            dp[0][j] = dp[0][j - 1] + grid[0][j];
        for (int i = 1; i < m; i++) {
            for (int j = 1; j < n; j++) {
                dp[i][j] = Math.min(dp[i - 1][j], dp[i][j - 1]) + grid[i][j];
            }
        }
        return dp[m - 1][n - 1];
    }
}

// Problem: Minimum Path Sum
// Problem Link: https://leetcode.com/problems/minimum-path-sum/
// Approach: Use bottom-up dynamic programming. Store the minimum path sum to reach each cell by taking the minimum of the top and left cells and adding the current cell's value.
// Time Complexity: O(m × n)
// Space Complexity: O(m × n)
